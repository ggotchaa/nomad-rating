/** Russian/Kazakh female form of a surname: Сейтов → Сейтова; Ким, Шевченко unchanged. */
export function surnameFor(surname: string, gender: 'm' | 'f'): string {
  if (gender === 'm') return surname
  return /(ов|ев|ин)$/.test(surname) ? `${surname}а` : surname
}

